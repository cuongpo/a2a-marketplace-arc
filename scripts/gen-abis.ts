// Generates src/shared/abis.ts from Foundry artifacts (contracts/out). Run after `forge build`.
import { readFileSync, writeFileSync } from 'node:fs'

const names = ['MissionEscrow', 'AgentBudgetVault', 'EvidenceRegistry', 'Erc8004Adapter'] as const
let out = '// GENERATED by scripts/gen-abis.ts from contracts/out. Do not edit by hand.\n'
for (const n of names) {
  const art = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, 'utf8')) as { abi: unknown[] }
  out += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(art.abi)} as const\n`
}
writeFileSync('src/shared/abis.ts', out)
console.log('wrote src/shared/abis.ts')
